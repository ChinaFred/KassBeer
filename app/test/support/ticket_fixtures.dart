import 'package:kass_beer/features/tickets/domain/ticket.dart';

/// Ticket de test ; [createdAt] vaut le 8 novembre 2026 sauf `null` explicite.
Ticket unTicket({
  String id = 't1',
  TicketType type = TicketType.bug,
  String title = 'Densité fausse',
  String description = 'La densité affichée est fausse.',
  String screen = '/recettes/:id',
  TicketStatus status = TicketStatus.received,
  String? appVersion = '0.1.0',
  String? platform = 'android',
  Object? createdAt = _defaultDate,
  DateTime? statusChangedAt,
  DateTime? seenByAuthorAt,
  String? replyText,
  String? deliveredPrUrl,
  String? deliveredVersion,
  String? authorEmail = 'brasseur@exemple.fr',
  int? issueNumber,
  String? issueUrl,
  int? deliveredPrNumber,
  int? sendAttempts,
  String? lastSendError,
  DateTime? issueMissingSince,
  List<TicketDecisionAction>? allowedDecisions,
  bool canAnswer = false,
  bool canLaunchAnalysis = false,
  bool canLaunchDevelopment = false,
  DateTime? decisionLeaseUntil,
  DateTime? retryRequestedAt,
  String? screenshotPath,
  bool hasPendingWrites = false,
}) => Ticket(
  id: id,
  type: type,
  title: title,
  description: description,
  screen: screen,
  status: status,
  appVersion: appVersion,
  platform: platform,
  createdAt: identical(createdAt, _defaultDate)
      ? DateTime(2026, 11, 8, 9, 30)
      : createdAt as DateTime?,
  statusChangedAt: statusChangedAt,
  seenByAuthorAt: seenByAuthorAt,
  replyText: replyText,
  deliveredPrUrl: deliveredPrUrl,
  deliveredVersion: deliveredVersion,
  authorEmail: authorEmail,
  issueNumber: issueNumber,
  issueUrl: issueUrl,
  deliveredPrNumber: deliveredPrNumber,
  sendAttempts: sendAttempts,
  lastSendError: lastSendError,
  issueMissingSince: issueMissingSince,
  allowedDecisions: allowedDecisions,
  canAnswer: canAnswer,
  canLaunchAnalysis: canLaunchAnalysis,
  canLaunchDevelopment: canLaunchDevelopment,
  decisionLeaseUntil: decisionLeaseUntil,
  retryRequestedAt: retryRequestedAt,
  screenshotPath: screenshotPath,
  hasPendingWrites: hasPendingWrites,
);

/// Décision de test, demandée le 8 novembre 2026 à 11 h.
TicketDecision uneDecision({
  String id = 'd1',
  TicketDecisionAction? action = TicketDecisionAction.refuse,
  TicketDecisionState state = TicketDecisionState.pending,
  String? text = 'Hors du périmètre.',
  DateTime? requestedAt,
  String? errorReason,
  DateTime? leaseUntil,
  bool hasPendingWrites = false,
}) => TicketDecision(
  id: id,
  action: action,
  state: state,
  text: text,
  requestedAt: requestedAt ?? DateTime(2026, 11, 8, 11),
  errorReason: errorReason,
  leaseUntil: leaseUntil,
  hasPendingWrites: hasPendingWrites,
);

const Object _defaultDate = Object();
